//While loop- similar to for loop
//While loop-->it will not run until the condition is true.
//Initialization--> done outside
//Condition--> to enter inside the loop
//Updation-->once condition is true, it will update the value

let attempt=1;

 while(attempt<=3){
  console.log(attempt + " Attempt");
  attempt++;
 } // once condition crosses the 3, it will come out of the loop.